"""The ``html`` key of a result, for the Backend's PDF: the summary and the names of the recommended tests."""
from __future__ import annotations

from collections.abc import Mapping
from html import escape
from typing import Any

LABELS = {
    "en": {"summary": "Summary", "tests": "Recommended follow-up tests"},
    "ar": {"summary": "الملخص", "tests": "الفحوصات الموصى بها"},
}
# The static message after the list of tests; the symptom one has the patient's symptom and its date (yyyy-MM-dd).
VISIT_MESSAGE = {
    "en": "These tests are recommended by our AI assistant. They are not a guarantee, and it is important to discuss "
          "them with your doctor, especially if any symptoms appear.",
    "ar": "هذه الفحوصات موصى بها من مساعدنا الذكي. وهي ليست ضمانًا، ومن المهم مناقشتها مع طبيبك، "
          "خاصة إذا ظهرت أي أعراض.",
}
SYMPTOM_MESSAGE = {
    "en": "Based on the symptoms you added on {date} ({symptom}), these tests are recommended. It is important to "
          "discuss with your doctor if any other symptoms appear. These AI-generated recommendations are not a "
          "guarantee.",
    "ar": "بناءً على الأعراض التي أضفتها بتاريخ {date} ({symptom})، هذه هي الفحوصات الموصى بها. من المهم مناقشة طبيبك "
          "إذا ظهرت أي أعراض أخرى. هذه التوصيات المولّدة بالذكاء الاصطناعي ليست ضمانًا.",
}
# The footer of every page, with or without recommended tests (a visit, a symptom check, a blocked answer).
FOOTER = {
    "en": "This summary was generated by an AI assistant and does not replace medical advice. Please discuss your "
          "results, and any symptoms you feel, with your doctor.",
    "ar": "تم إنشاء هذا الملخص بواسطة مساعد ذكي ولا يغني عن الاستشارة الطبية. يرجى مناقشة نتائجك، وأي أعراض تشعر بها، "
          "مع طبيبك.",
}
WRAPPER = {"en": '<div lang="en">{}</div>', "ar": '<div lang="ar" dir="rtl">{}</div>'}


def _text(node: Any, lang: str) -> str:
    value = node.get(lang) if isinstance(node, Mapping) else None
    return escape(str(value)) if value else ""


def _test_names(ai: Mapping[str, Any], lang: str, arabic_names: Mapping[str, str], with_reasons: bool) -> list[str]:
    """Names of the recommended tests, each with its reason if asked. A test the symptom check removed is not
    recommended any more."""
    names = []
    for rec in ai.get("recommendations") or []:
        if (rec.get("change_type") or {}).get("en") == "removed":
            continue
        name = str(rec.get("test_name", ""))
        item = escape(arabic_names.get(name, name) if lang == "ar" else name)
        if reason := _text(rec.get("reason"), lang) if with_reasons else "":
            item += f" - {reason}"
        names.append(item)
    return names


def build_html(
    ai: Mapping[str, Any], arabic_names: Mapping[str, str] | None = None, with_reasons: bool = False,
    symptom: tuple[str, str] | None = None,
) -> dict[str, str]:
    """``{"en": "<div ...>", "ar": "<div dir=rtl ...>"}``: the summary, one bullet per recommended test, then the
    static message (only when a test is listed), and always the footer (``FOOTER``: AI-generated, see your doctor).

    ``arabic_names`` maps an English test name to ``tests.test_name_ar``; a test without one keeps its English name.
    ``with_reasons`` adds each test's reason (the symptom check shows them). ``symptom`` is the patient's symptom text
    and its date for the symptom check's message; None (a visit) gives the visit message. All text is HTML-escaped.
    """
    arabic_names = arabic_names or {}
    pages = {}
    for lang, words in LABELS.items():
        parts = []
        summary = _text(ai.get("summary"), lang)
        if summary:
            parts += [f"<h2>{words['summary']}</h2>", f"<p>{summary}</p>"]
        names = _test_names(ai, lang, arabic_names, with_reasons)
        if names:
            message = (SYMPTOM_MESSAGE[lang].format(date=symptom[1], symptom=escape(symptom[0])) if symptom
                       else VISIT_MESSAGE[lang])
            parts += [f"<h2>{words['tests']}</h2>", "<ul>" + "".join(f"<li>{name}</li>" for name in names) + "</ul>",
                      f"<p>{message}</p>"]
        parts.append(f"<p><small>{FOOTER[lang]}</small></p>")
        pages[lang] = WRAPPER[lang].format("".join(parts))
    return pages
