"""The ``html`` key of a result, for the Backend's PDF: header, summary, recommended tests with reasons, one footer."""
from __future__ import annotations

from collections.abc import Mapping
from html import escape
from typing import Any

# Fixed words of the page. Written once, so the legal wording is the same in every report and never comes from the AI.
LABELS = {
    "en": {"title": "AI-Generated Patient Test Result Summary", "summary": "Summary",
           "tests": "Recommended follow-up tests", "reason": "Reason"},
    "ar": {"title": "ملخص نتائج تحاليل المريض المُنشأ بالذكاء الاصطناعي", "summary": "الملخص",
           "tests": "الفحوصات الموصى بها", "reason": "السبب"},
}
# Under the tests heading of a symptom check: the patient's symptom and its date (yyyy-MM-dd).
SYMPTOM_MESSAGE = {
    "en": "Based on the symptoms you added on {date} ({symptom}).",
    "ar": "بناءً على الأعراض التي أضفتها بتاريخ {date} ({symptom}).",
}
# Instead of the tests when the AI recommends none (an empty list, or every test removed by a symptom check).
NO_TESTS = {
    "en": "No specific follow-up tests are recommended based on the current visit's results.",
    "ar": "لا توجد فحوصات متابعة محددة موصى بها بناءً على نتائج الزيارة الحالية.",
}
# The only notice of every page, with or without recommended tests (a visit, a symptom check, a blocked answer).
FOOTER = {
    "en": "This report was generated by an AI assistant. It is not a diagnosis and does not replace medical advice. "
          "Discuss your results and any symptoms with your doctor. If you feel severely unwell, seek urgent care.",
    "ar": "تم إنشاء هذا التقرير بواسطة مساعد ذكي. وهو ليس تشخيصًا ولا يغني عن الاستشارة الطبية. ناقش نتائجك وأي أعراض "
          "تشعر بها مع طبيبك. وإذا شعرت بتعب شديد، فاطلب الرعاية الطبية العاجلة.",
}
# Inline styles only (no <style> block): the Backend's PDF engine keeps them, a stylesheet may be dropped.
FONT = "font-family:Arial,Helvetica,sans-serif;color:#222;line-height:1.55;font-size:14px"
WRAPPER = {"en": f'<div lang="en" style="{FONT}">{{}}</div>',
           "ar": f'<div lang="ar" dir="rtl" style="{FONT}">{{}}</div>'}
H1 = '<h1 style="margin:0 0 16px;font-size:22px">{}</h1>'
H2 = '<h2 style="margin:24px 0 8px;font-size:18px">{}</h2>'
# One paragraph per test: its gap survives even when a viewer drops the style (a list's padding and markers did not).
TEST = '<p style="margin:0 0 14px">{}</p>'
FOOTER_HTML = ('<hr style="margin:24px 0 10px;border:0;border-top:1px solid #bbb">'
               '<p style="margin:0;font-size:12px;color:#555">{}</p>')


def _text(node: Any, lang: str) -> str:
    value = node.get(lang) if isinstance(node, Mapping) else None
    return escape(str(value)) if value else ""


def _tests(ai: Mapping[str, Any], lang: str, arabic_names: Mapping[str, str]) -> list[str]:
    """One numbered paragraph per recommended test: ``1. name - priority``, then the reason (each only if the answer
    has it). The number is text, not a list marker (a viewer that drops the list's padding hides the markers); its
    ``dir="ltr"`` keeps ``1.`` from showing as ``.1`` in Arabic. A test the symptom check removed is not recommended
    any more, and the numbers go on without a gap."""
    recs = [r for r in ai.get("recommendations") or [] if (r.get("change_type") or {}).get("en") != "removed"]
    blocks = []
    for number, rec in enumerate(recs, 1):
        name = str(rec.get("test_name", ""))
        block = (f'<strong><span dir="ltr">{number}.</span> '
                 f"{escape(arabic_names.get(name, name) if lang == 'ar' else name)}</strong>")
        if priority := _text(rec.get("priority"), lang):
            block += f" - {priority.capitalize()}"
        if reason := _text(rec.get("reason"), lang):
            block += f'<br><u>{LABELS[lang]["reason"]}</u>: {reason}'
        blocks.append(TEST.format(block))
    return blocks


def build_html(
    ai: Mapping[str, Any], arabic_names: Mapping[str, str] | None = None, symptom: tuple[str, str] | None = None,
) -> dict[str, str]:
    """``{"en": "<div ...>", "ar": "<div dir=rtl ...>"}``: the header (title with the AI label), the summary, the
    recommended tests (numbered, with priority and reason; ``NO_TESTS`` when there are none; no section for a blocked
    answer), and always one footer (``FOOTER``: AI-generated, not a diagnosis, see your doctor, urgent care).

    ``arabic_names`` maps an English test name to ``tests.test_name_ar``; a test without one keeps its English name.
    ``symptom`` is the patient's symptom text and its date for the symptom check's line under the tests heading.
    All text is HTML-escaped."""
    arabic_names = arabic_names or {}
    pages = {}
    for lang, words in LABELS.items():
        parts = [H1.format(words["title"])]
        if summary := _text(ai.get("summary"), lang):
            parts += [H2.format(words["summary"]), f'<p style="margin:0">{summary}</p>']
        tests = _tests(ai, lang, arabic_names)
        if tests or ai.get("recommendations") is not None:       # None = a blocked answer: no tests section at all
            parts.append(H2.format(words["tests"]))
            if symptom:
                line = SYMPTOM_MESSAGE[lang].format(date=symptom[1], symptom=escape(symptom[0]))
                parts.append(f'<p style="margin:0 0 12px">{line}</p>')
            parts += tests or [TEST.format(NO_TESTS[lang])]
        parts.append(FOOTER_HTML.format(FOOTER[lang]))
        pages[lang] = WRAPPER[lang].format("".join(parts))
    return pages
